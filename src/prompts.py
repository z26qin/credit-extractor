"""Prompt strings and clause-name canon.

The CUAD prompt is copied verbatim from Model B's model card (Apache-2.0), which says the
model was trained on exactly this shape and anything else is out of distribution. Do not
edit these strings: tests pin them byte-for-byte. The credit prompt keeps that shape and
adds the clause list from configs/credit_schema.yaml.
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent

CUAD_SYSTEM = ("You are a contract review system. Extract the requested clause types from the "
               "contract excerpt. Quote the contract text verbatim. A clause type not present "
               "in this excerpt gets an empty list. Reply with JSON only.")
CUAD_USER_PREFIX = ("Extract all 41 CUAD clause types from this contract excerpt as JSON "
                    "(keys: clause types, values: lists of verbatim quotes).\n\nCONTRACT EXCERPT:\n")


def load_cuad_clauses(path: Path | None = None) -> list[str]:
    """The 41 CUAD clause names in official order (data/category_descriptions.csv, CC BY 4.0)."""
    path = path or REPO_ROOT / "data" / "category_descriptions.csv"
    with open(path, encoding="utf-8-sig") as f:
        rows = list(csv.reader(f))[1:]
    clauses = [r[0].replace("Category: ", "").strip() for r in rows]
    if len(clauses) != 41:
        raise ValueError(f"expected 41 CUAD clause types, got {len(clauses)}")
    return clauses


def norm_key(s: str) -> str:
    """Key used to map model output keys back to canonical clause names."""
    return re.sub(r"[^a-z0-9]", "", str(s).lower())


def canon_map(clauses: list[str]) -> dict[str, str]:
    m = {norm_key(c): c for c in clauses}
    if len(m) != len(clauses):
        raise ValueError("clause names collide after normalization")
    return m


def messages(system: str, user_prefix: str, chunk_text: str) -> list[dict]:
    return [{"role": "system", "content": system},
            {"role": "user", "content": user_prefix + chunk_text}]


def load_credit_schema(path: Path | None = None) -> dict:
    return yaml.safe_load(Path(path or REPO_ROOT / "configs" / "credit_schema.yaml").read_text())


def credit_clauses(schema: dict | None = None) -> list[str]:
    return [c["name"] for c in (schema or load_credit_schema())["clauses"]]


def credit_user_prefix(schema: dict | None = None) -> str:
    """Model B's user turn with the clause list swapped in. The system turn stays identical."""
    clauses = (schema or load_credit_schema())["clauses"]
    lines = "\n".join(f"- {c['name']}: {c['definition']}" for c in clauses)
    return (f"Extract all {len(clauses)} credit clause types from this contract excerpt as JSON "
            "(keys: clause types, values: lists of verbatim quotes).\n\n"
            f"CLAUSE TYPES:\n{lines}\n\nCONTRACT EXCERPT:\n")


PROMPTS = {
    # name -> (system, user_prefix)
    "cuad_native": (CUAD_SYSTEM, CUAD_USER_PREFIX),
    "credit_schema": (CUAD_SYSTEM, credit_user_prefix()),
}

CHUNK_PLACEHOLDER = "<CHUNK TEXT>"


def render_report(tokenizer_for) -> str:
    """Markdown with each condition's exact prompt; `tokenizer_for(model)` gives its tokenizer."""
    L = ["# Milestone 2: rendered prompts", "",
         f"Generated by `python -m src.prompts`. `{CHUNK_PLACEHOLDER}` stands for the chunk; "
         "everything else is the exact text sent to the model.", ""]
    rendered = {}
    for c in load_credit_schema()["conditions"]:
        tok = tokenizer_for(c["model"])
        system, prefix = PROMPTS[c["prompt"]]
        text = tok.apply_chat_template(messages(system, prefix, CHUNK_PLACEHOLDER),
                                       tokenize=False, add_generation_prompt=True)
        rendered[c["id"]] = text
        n = len(tok(text, add_special_tokens=False)["input_ids"])
        L += [f"## Condition {c['id']}: {c['label']}", "", f"- Model: `{c['model']}`",
              f"- Prompt: `{c['prompt']}`, {n} tokens before the chunk text", "",
              "```text", text.rstrip("\n"), "```", ""]
    same = len({t for k, t in rendered.items() if k != "a"}) == 1
    L += [f"Conditions b and c render to the same text: {'yes' if same else 'NO'}.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    from transformers import AutoTokenizer
    out = REPO_ROOT / "reports" / "m2_prompts.md"
    out.write_text(render_report(AutoTokenizer.from_pretrained), encoding="utf-8")
    print(out)
